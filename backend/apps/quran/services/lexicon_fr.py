def translate_word(arabic_word: str) -> str | None:
    """
    Traduction française d'un mot coranique, ou None si absent du lexique
    (l'appelant bascule alors sur la traduction anglaise de Quran.com).
    """
    key = normalize_arabic(arabic_word)
    if not key:
        return None
    return LEXICON.get(key)