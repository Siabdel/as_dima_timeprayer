"""
Lexique français mot-à-mot pour le Coran.

Quran.com v4 ne fournit les traductions mot à mot qu'en anglais (paramètre
`word_translation_language` ignoré). Pour offrir une lecture mot à mot en
français, l'application s'appuie sur :

1. Ce lexique LOCAL : traduction française des mots coraniques les plus
   fréquents (Allah, Seigneur, miséricordieux, prière, foi…), normalisés
   en retirant les diacritiques (harakât) et les marques Uthmani.
2. Un FALLBACK intelligent : si le mot n'est pas dans le lexique, on affiche
   la traduction anglaise de Quran.com (champ `translation`) — le lecteur
   conserve toujours un sens, jamais un vide.

La clé de recherche est le mot arabe « nu » (sans harakât, alif/hamza
normalisés, tâ marbûta → hâ). Exemple :
  "بِسْمِ"          → "بسم"   → « au nom de »
  "ٱلرَّحْمَـٰنِ"  → "الرحمن" → « le Tout Miséricordieux »
"""

import re
import unicodedata

# Plages des diacritiques arabes (harakât) et marques coraniques (Uthmani).
_DIACRITICS = re.compile(r"[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED\u08D3-\u08E1\u08E3-\u08FF]")


def normalize_arabic(word: str) -> str:
    """
    Retire les diacritiques et normalise les formes d'alif pour obtenir une
    clé de lexique stable.

    Ex. « ٱللَّهِ » → « الله », « بِسْمِ » → « بسم », « ٱلرَّحْمَـٰنِ » → « الرحمن ».
    """
    if not word:
        return ""
    # Remplacement caractère par caractère : on retire les harakât,
    # la kasra d'alif (ٱ = alif wasla) devient alif simple.
    cleaned = _DIACRITICS.sub("", word)
    cleaned = cleaned.replace("\u0670", "")      # alif suscrit (petit alif)
    cleaned = cleaned.replace("\u0653", "")      # madda
    cleaned = cleaned.replace("\u06E1", "")      # signe Uthmani (sukun rond)
    cleaned = cleaned.replace("\u0640", "")      # tatweel (trait de prolongation)
    cleaned = unicodedata.normalize("NFKC", cleaned)
    # Normalisations orthographiques courantes.
    cleaned = (
        cleaned.replace("\u0671", "\u0627")      # alif wasla → alif
        .replace("\u0622", "\u0627")             # alif madda → alif
        .replace("\u0623", "\u0627")             # alif hamza haut → alif
        .replace("\u0625", "\u0627")             # alif hamza bas → alif
        .replace("\u0629", "\u0647")             # tâ marbûta → hâ
        .replace("\u0649", "\u064A")             # alif maqsûra → yâ
    )
    return cleaned.strip()


